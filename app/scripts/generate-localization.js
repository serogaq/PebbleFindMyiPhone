'use strict';

var fs = require('fs');
var path = require('path');

var FILES = ['watch.json', 'settings.json'];
var KEY_PATTERN = /^[a-z][a-z0-9_]*$/;
var LOCALE_PATTERN = /^[A-Za-z]{2,3}(?:[-_][A-Za-z0-9]{2,8})*$/;

function normalizeLocale(value) {
  return String(value || '').trim().replace(/_/g, '-').toLowerCase();
}

function readDictionary(filename) {
  var parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(filename, 'utf8'));
  } catch (error) {
    throw new Error('Cannot read localization file ' + filename + ': ' + error.message);
  }
  if (!parsed || Array.isArray(parsed) || typeof parsed !== 'object') {
    throw new Error('Localization file must contain a JSON object: ' + filename);
  }
  Object.keys(parsed).forEach(function(key) {
    if (!KEY_PATTERN.test(key)) {
      throw new Error('Invalid localization key "' + key + '" in ' + filename);
    }
    if (typeof parsed[key] !== 'string') {
      throw new Error('Localization value must be a string for "' + key + '" in ' + filename);
    }
  });
  return parsed;
}

function loadCatalogs(root) {
  if (!fs.existsSync(root)) {
    throw new Error('Localization directory does not exist: ' + root);
  }
  var catalogs = {};
  var sourceNames = {};
  fs.readdirSync(root, {withFileTypes: true})
    .filter(function(entry) { return entry.isDirectory() && entry.name.charAt(0) !== '.'; })
    .sort(function(a, b) { return a.name.localeCompare(b.name); })
    .forEach(function(entry) {
      if (!LOCALE_PATTERN.test(entry.name)) {
        throw new Error('Invalid locale directory name: ' + entry.name);
      }
      var normalized = normalizeLocale(entry.name);
      if (catalogs[normalized]) {
        throw new Error('Locale directories normalize to the same name: ' +
          sourceNames[normalized] + ' and ' + entry.name);
      }
      var directory = path.join(root, entry.name);
      catalogs[normalized] = {};
      sourceNames[normalized] = entry.name;
      FILES.forEach(function(filename) {
        var fullPath = path.join(directory, filename);
        if (!fs.existsSync(fullPath)) {
          throw new Error('Missing localization file: ' + fullPath);
        }
        catalogs[normalized][filename.slice(0, -5)] = readDictionary(fullPath);
      });
    });
  if (!catalogs.en) {
    throw new Error('English fallback locale app/localization/en is required');
  }
  return catalogs;
}

function mergedDictionary(english, translated, locale, kind) {
  Object.keys(translated).forEach(function(key) {
    if (!Object.prototype.hasOwnProperty.call(english, key)) {
      throw new Error('Locale ' + locale + ' has unknown ' + kind + ' key: ' + key);
    }
  });
  var merged = {};
  Object.keys(english).sort().forEach(function(key) {
    var value = translated[key];
    merged[key] = typeof value === 'string' && value.trim() ? value : english[key];
  });
  return merged;
}

function cIdentifier(value) {
  return value.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
}

function cString(value) {
  var escaped = value.replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t');
  return '"' + escaped + '"';
}

function twoDigits(value) {
  return value < 10 ? '0' + value : String(value);
}

function formatBuildTime(date) {
  var months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
    'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  return months[date.getUTCMonth()] + ' ' + date.getUTCDate() + ', ' +
    date.getUTCFullYear() + ' ' + twoDigits(date.getUTCHours()) + ':' +
    twoDigits(date.getUTCMinutes()) + ':' + twoDigits(date.getUTCSeconds()) + ' GMT';
}

function renderCHeader(keys) {
  var lines = [
    '/* Generated by scripts/generate-localization.js. Do not edit. */',
    '#pragma once',
    '',
    'typedef enum {'
  ];
  keys.forEach(function(key, index) {
    lines.push('  WATCH_STRING_' + cIdentifier(key) + ' = ' + index + ',');
  });
  lines.push('  WATCH_STRING_COUNT = ' + keys.length + ',');
  lines.push('} WatchString;');
  lines.push('');
  lines.push('void localization_init(const char *system_locale);');
  lines.push('const char *localization_get(WatchString key);');
  lines.push('');
  return lines.join('\n');
}

function renderCSource(catalogs, keys) {
  var locales = Object.keys(catalogs).sort();
  var english = catalogs.en.watch;
  var lines = [
    '/* Generated by scripts/generate-localization.js. Do not edit. */',
    '#include "localization.auto.h"',
    '',
    '#include <stddef.h>',
    '#include <string.h>',
    ''
  ];
  locales.forEach(function(locale) {
    var dictionary = mergedDictionary(english, catalogs[locale].watch, locale, 'watch');
    lines.push('static const char *const s_locale_' + cIdentifier(locale).toLowerCase() +
      '[WATCH_STRING_COUNT] = {');
    keys.forEach(function(key) {
      lines.push('  [WATCH_STRING_' + cIdentifier(key) + '] = ' + cString(dictionary[key]) + ',');
    });
    lines.push('};');
    lines.push('');
  });
  lines.push('typedef struct {');
  lines.push('  const char *name;');
  lines.push('  const char *const *strings;');
  lines.push('} LocaleEntry;');
  lines.push('');
  lines.push('static const LocaleEntry s_locales[] = {');
  locales.forEach(function(locale) {
    lines.push('  {' + cString(locale) + ', s_locale_' + cIdentifier(locale).toLowerCase() + '},');
  });
  lines.push('};');
  lines.push('');
  lines.push('static const char *const *s_current = s_locale_en;');
  lines.push('');
  lines.push('static void prv_normalize_locale(const char *source, char *target, size_t size) {');
  lines.push('  size_t index = 0;');
  lines.push('  if (!source || size == 0) {');
  lines.push('    return;');
  lines.push('  }');
  lines.push('  while (*source && *source != \'.\' && *source != \'@\' && index + 1 < size) {');
  lines.push('    char value = *source++;');
  lines.push('    if (value == \'_\') {');
  lines.push('      value = \'-\';');
  lines.push('    } else if (value >= \'A\' && value <= \'Z\') {');
  lines.push('      value = (char)(value - \'A\' + \'a\');');
  lines.push('    }');
  lines.push('    target[index++] = value;');
  lines.push('  }');
  lines.push('  target[index] = \'\\0\';');
  lines.push('}');
  lines.push('');
  lines.push('static const char *const *prv_find_locale(const char *name) {');
  lines.push('  for (size_t index = 0; index < sizeof(s_locales) / sizeof(s_locales[0]); index++) {');
  lines.push('    if (strcmp(name, s_locales[index].name) == 0) {');
  lines.push('      return s_locales[index].strings;');
  lines.push('    }');
  lines.push('  }');
  lines.push('  return NULL;');
  lines.push('}');
  lines.push('');
  lines.push('void localization_init(const char *system_locale) {');
  lines.push('  char locale[32] = {0};');
  lines.push('  prv_normalize_locale(system_locale, locale, sizeof(locale));');
  lines.push('  while (locale[0]) {');
  lines.push('    const char *const *strings = prv_find_locale(locale);');
  lines.push('    if (strings) {');
  lines.push('      s_current = strings;');
  lines.push('      return;');
  lines.push('    }');
  lines.push('    char *separator = strrchr(locale, \'-\');');
  lines.push('    if (!separator) {');
  lines.push('      break;');
  lines.push('    }');
  lines.push('    *separator = \'\\0\';');
  lines.push('  }');
  lines.push('  s_current = s_locale_en;');
  lines.push('}');
  lines.push('');
  lines.push('const char *localization_get(WatchString key) {');
  lines.push('  if ((unsigned int)key >= WATCH_STRING_COUNT) {');
  lines.push('    return "";');
  lines.push('  }');
  lines.push('  const char *value = s_current[key];');
  lines.push('  return value ? value : s_locale_en[key];');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

function renderSettingsModule(catalogs, buildInfo) {
  var resolved = {};
  Object.keys(catalogs).sort().forEach(function(locale) {
    resolved[locale] = mergedDictionary(
      catalogs.en.settings, catalogs[locale].settings, locale, 'settings');
  });
  return [
    '/* Generated by scripts/generate-localization.js. Do not edit. */',
    '\'use strict\';',
    '',
    'module.exports = ' + JSON.stringify({
      locales: resolved,
      build: buildInfo
    }, null, 2) + ';',
    ''
  ].join('\n');
}

function writeIfChanged(filename, content) {
  if (fs.existsSync(filename) && fs.readFileSync(filename, 'utf8') === content) {
    return;
  }
  fs.mkdirSync(path.dirname(filename), {recursive: true});
  fs.writeFileSync(filename, content, 'utf8');
}

function generate(projectRoot) {
  var catalogs = loadCatalogs(path.join(projectRoot, 'localization'));
  var packageInfo = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8'));
  var buildInfo = {
    version: packageInfo.version,
    built_at: formatBuildTime(new Date())
  };
  var watchKeys = Object.keys(catalogs.en.watch).sort();
  watchKeys.forEach(function(key) {
    if (!catalogs.en.watch[key].trim()) {
      throw new Error('English fallback watch value is empty: ' + key);
    }
  });
  Object.keys(catalogs.en.settings).forEach(function(key) {
    if (!catalogs.en.settings[key].trim()) {
      throw new Error('English fallback settings value is empty: ' + key);
    }
  });
  writeIfChanged(path.join(projectRoot, 'src/c/localization.auto.h'), renderCHeader(watchKeys));
  writeIfChanged(path.join(projectRoot, 'src/c/localization.auto.c'),
    renderCSource(catalogs, watchKeys));
  writeIfChanged(path.join(projectRoot, 'src/pkjs/lib/settings-locales.auto.js'),
    renderSettingsModule(catalogs, buildInfo));
  return catalogs;
}

if (require.main === module) {
  try {
    generate(path.resolve(__dirname, '..'));
  } catch (error) {
    console.error('error: ' + error.message);
    process.exit(1);
  }
}

module.exports = {
  FILES: FILES,
  formatBuildTime: formatBuildTime,
  generate: generate,
  loadCatalogs: loadCatalogs,
  normalizeLocale: normalizeLocale,
  renderCHeader: renderCHeader,
  renderCSource: renderCSource,
  renderSettingsModule: renderSettingsModule
};
